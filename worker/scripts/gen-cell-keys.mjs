// Generate src/cellKeys.js — the curated-cell allowlist the Worker uses to
// reject ensure-fresh for coordinates that aren't real servable cells (bots /
// hand-typed coords). data/cells.csv (repo root) is the source of truth; this
// emits a Set of snapped "lat_lon" keys built with the SAME cellKey() the Worker
// uses at request time, so the allowlist and a live request can't disagree on
// formatting. Wired to predev/predeploy so it can't drift from cells.csv.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { cellKey } from '../src/cellStore.js';

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, '../../data/cells.csv');
const dest = resolve(here, '../src/cellKeys.js');

const lines = readFileSync(src, 'utf8').split(/\r?\n/).filter(Boolean);
const header = lines[0].split(',');
const latI = header.indexOf('lat');
const lonI = header.indexOf('lon');
if (latI < 0 || lonI < 0) throw new Error('cells.csv missing lat/lon columns');

const keys = new Set();
for (const line of lines.slice(1)) {
  // commas only appear inside the trailing quoted name, which we don't read.
  const cols = line.split(',');
  keys.add(cellKey(parseFloat(cols[latI]), parseFloat(cols[lonI])));
}

const sorted = [...keys].sort();
const body = `// GENERATED by scripts/gen-cell-keys.mjs from data/cells.csv — do not edit.
// The curated-cell allowlist for /api/ensure-fresh: snapped "lat_lon" keys for
// every servable cell. Regenerated on predev/predeploy so it tracks cells.csv.
export const CELL_KEYS = new Set(
  '${sorted.join(' ')}'.split(' '),
);
`;

writeFileSync(dest, body);
console.log(`wrote ${sorted.length} cell keys → ${dest}`);
